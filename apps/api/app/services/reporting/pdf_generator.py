    def _render_reportlab_fallback(self, case: CaseRecord, result: CaseResult) -> bytes:
        buffer = BytesIO()
        pdf = canvas.Canvas(buffer, pagesize=A4)
        width, height = A4

        referral_style = REFERRAL_STYLES[result.referral_urgency]
        fallback_colors = {
            "referral-safe": "#22C55E",
            "referral-routine": "#F59E0B",
            "referral-urgent": "#F97316",
            "referral-emergency": "#EF4444",
        }

        pdf.setTitle(f"Visara Report - {case.id}")
        pdf.setFillColor(colors.HexColor("#0F1629"))
        pdf.rect(0, height - 80, width, 80, fill=1, stroke=0)
        pdf.setFillColor(colors.white)
        pdf.setFont("Helvetica-Bold", 18)
        pdf.drawString(36, height - 42, "Visara")
        pdf.setFont("Helvetica", 11)
        pdf.drawRightString(width - 36, height - 42, "AI-Assisted DR Screening Report")

        current_y = height - 118
        pdf.setFillColor(colors.HexColor("#0F1629"))
        pdf.setFont("Helvetica", 10)
        pdf.drawString(36, current_y, f"Patient Reference: {case.patient_ref}")
        pdf.drawRightString(width - 36, current_y, f"Case ID: {case.id}")
        current_y -= 16
        pdf.drawString(36, current_y, f"Eye: {case.eye_side.title()}")
        pdf.drawRightString(width - 36, current_y, f"Date & Time: {self._format_datetime(case.created_at)}")
        current_y -= 16
        pdf.drawString(36, current_y, f"Referring operator: {self._get_operator_name(case)}")

        current_y -= 38
        pdf.setFillColor(colors.HexColor(fallback_colors[referral_style["class_name"]]))
        pdf.roundRect(36, current_y - 50, width - 72, 52, 10, fill=1, stroke=0)
        pdf.setFillColor(colors.white)
        pdf.setFont("Helvetica-Bold", 16)
        pdf.drawString(50, current_y - 20, referral_style["title"])
        pdf.setFont("Helvetica", 10)
        pdf.drawString(50, current_y - 36, result.referral_label)

        current_y -= 78
        pdf.setFillColor(colors.HexColor("#0F1629"))
        pdf.setFont("Helvetica-Bold", 11)
        pdf.drawString(36, current_y, "Findings summary")
        pdf.setFont("Helvetica", 10)
        pdf.drawString(36, current_y - 16, f"DR Grade: Grade {result.grade} — {result.grade_label}")
        pdf.drawString(36, current_y - 32, f"Confidence: {result.confidence_tier.title()} confidence")
        pdf.drawString(36, current_y - 48, result.confidence_explanation[:120])

        assets = self._build_report_assets(case, result)
        if assets.original_image_uri:
            with Image.open(BytesIO(base64.b64decode(assets.original_image_uri.split(",", 1)[1]))) as original_image:
                pdf.drawImage(ImageReader(original_image), 36, current_y - 210, width=220, height=160, preserveAspectRatio=True)
        if assets.composite_image_uri:
            with Image.open(BytesIO(base64.b64decode(assets.composite_image_uri.split(",", 1)[1]))) as overlay_image:
                pdf.drawImage(
                    ImageReader(overlay_image),
                    width - 256,
                    current_y - 210,
                    width=220,
                    height=160,
                    preserveAspectRatio=True,
                )
        pdf.setFont("Helvetica", 9)
        pdf.drawString(36, current_y - 222, "Left: Original fundus image. Right: AI-detected lesion overlay.")

        table_y = current_y - 258
        pdf.setFont("Helvetica-Bold", 11)
        pdf.drawString(36, table_y, "Lesion findings")
        pdf.setFont("Helvetica", 10)
        row_y = table_y - 18
        for channel, label in CHANNEL_LABELS.items():
            pdf.drawString(36, row_y, label)
            pdf.drawRightString(width - 36, row_y, "Yes" if result.lesion_presence.get(channel) else "No")
            row_y -= 14

        if case.notes:
            row_y -= 8
            pdf.setFont("Helvetica-Bold", 11)
            pdf.drawString(36, row_y, "Clinical notes")
            pdf.setFont("Helvetica", 10)
            pdf.drawString(36, row_y - 16, case.notes[:220])
            row_y -= 34

        row_y -= 6
        pdf.setFont("Helvetica-Bold", 11)
        pdf.drawString(36, row_y, "Model information")
        pdf.setFont("Helvetica", 10)
        pdf.drawString(36, row_y - 16, f"Model: {result.model_version}")
        pdf.drawString(36, row_y - 32, "Architecture: Dual-encoder (RETFound ViT-L + SAM ViT-H)")
        pdf.drawString(36, row_y - 48, "Validation performance: QWK 0.853, RefAUC 0.926 (FGADR benchmark)")
        pdf.drawString(36, row_y - 64, "Training institution: BITS Pilani")

        pdf.setStrokeColor(colors.HexColor("#CBD5E1"))
        pdf.line(36, 62, width - 36, 62)
        pdf.setFont("Helvetica", 8)
        pdf.setFillColor(colors.HexColor("#334155"))
        pdf.drawString(36, 48, REPORT_DISCLAIMER[:145])
        pdf.drawString(36, 36, REPORT_DISCLAIMER[145:290])
        pdf.drawString(36, 24, f"Visara | BITS Pilani Research | {self._format_footer_date(result.processed_at)}")

        pdf.save()
        buffer.seek(0)
        return buffer.getvalue()
