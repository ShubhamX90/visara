logger = structlog.get_logger(__name__)

REPORT_DISCLAIMER = (
    "DISCLAIMER: This report is generated by an AI clinical decision-support system and is intended to "
    "assist, not replace, the clinical judgment of a qualified ophthalmologist. All clinical decisions "
    "remain the sole responsibility of the treating physician. This tool has not been approved as a "
    "standalone diagnostic device. For research and screening support purposes only."
)

CHANNEL_LABELS = {
    "ma": "Microaneurysms",
    "he": "Hard Exudates",
    "hem": "Haemorrhages",
    "se": "Soft Exudates",
    "irma": "IRMA",
    "nv": "Neovascularisation",
}

REFERRAL_STYLES = {
    "none": {"class_name": "referral-safe", "title": "NO REFERRAL REQUIRED"},
    "routine": {"class_name": "referral-routine", "title": "REFER TO OPHTHALMOLOGIST"},
    "urgent": {"class_name": "referral-urgent", "title": "REFER TO OPHTHALMOLOGIST"},
    "emergency": {"class_name": "referral-emergency", "title": "REFER TO OPHTHALMOLOGIST"},
}

TEMPLATE_DIR = Path(__file__).resolve().parent / "templates"


@dataclass(slots=True)
class ReportAssets:
    original_image_uri: str | None
    composite_image_uri: str | None


class PDFReportGenerator:
    def __init__(self, settings: Settings, storage: StorageBackend) -> None:
        self.settings = settings
        self.storage = storage
        self.html_template = Template((TEMPLATE_DIR / "report.html").read_text(encoding="utf-8"))
        self.css_template = (TEMPLATE_DIR / "report.css").read_text(encoding="utf-8")

    async def generate_case_report(self, *, case: CaseRecord, result: CaseResult) -> bytes:
        return await asyncio.to_thread(self._render_report, case, result)

    def _render_report(self, case: CaseRecord, result: CaseResult) -> bytes:
        html_document = self._build_html(case, result)

        try:
            from weasyprint import CSS, HTML
        except (ImportError, OSError) as exc:
            logger.warning("weasyprint_unavailable_falling_back_to_reportlab", detail=str(exc))
            return self._render_reportlab_fallback(case, result)

        return HTML(
            string=html_document,
            base_url=str(TEMPLATE_DIR),
        ).write_pdf(stylesheets=[CSS(string=self.css_template)])

    def _build_html(self, case: CaseRecord, result: CaseResult) -> str:
        report_assets = self._build_report_assets(case, result)
        referral_style = REFERRAL_STYLES[result.referral_urgency]

        original_figure = self._build_figure_block(
            title="Original fundus image",
            image_uri=report_assets.original_image_uri,
            fallback_message="Preview unavailable for this file format.",
        )
        overlay_figure = self._build_figure_block(
            title="Composite lesion overlay",
            image_uri=report_assets.composite_image_uri,
            fallback_message="Overlay preview unavailable.",
        )
        notes_section = self._build_notes_section(case.notes)
        lesion_rows = self._build_lesion_rows(result)

        return self.html_template.safe_substitute(
            logo_data_uri=self._build_logo_data_uri(),
            patient_ref=escape(case.patient_ref),
            case_id=escape(case.id),
            eye_side=escape(case.eye_side.title()),
            case_datetime=escape(self._format_datetime(case.created_at)),
            operator_name=escape(self._get_operator_name(case)),
            referral_class=referral_style["class_name"],
            referral_decision=escape(referral_style["title"]),
            referral_label=escape(result.referral_label),
            grade_display=escape(f"Grade {result.grade} — {result.grade_label}"),
            confidence_tier=escape(f"{result.confidence_tier.title()} confidence"),
            confidence_explanation=escape(result.confidence_explanation),
            clinical_summary=escape(result.clinical_summary),
            original_figure=original_figure,
            overlay_figure=overlay_figure,
            lesion_rows=lesion_rows,
            notes_section=notes_section,
            model_version=escape(result.model_version),
            processed_at=escape(self._format_datetime(result.processed_at)),
            report_footer_date=escape(self._format_footer_date(result.processed_at)),
            disclaimer_text=escape(REPORT_DISCLAIMER),
        )

    def _build_report_assets(self, case: CaseRecord, result: CaseResult) -> ReportAssets:
        original_image = self._load_original_image(case)
        original_uri = self._image_to_data_uri(original_image) if original_image is not None else None
        composite_uri = self._image_to_data_uri(self._build_composite_overlay(original_image, result))
        return ReportAssets(original_image_uri=original_uri, composite_image_uri=composite_uri)

    def _load_original_image(self, case: CaseRecord) -> Image.Image | None:
        if not (case.image_content_type.startswith("image/") or case.image_content_type == "application/dicom"):
            return None

        try:
            payload = asyncio.run(self.storage.read_bytes(case.image_storage_path))
            image = load_source_image_bytes(
                payload=payload,
                content_type=case.image_content_type,
                filename=case.image_original_filename,
            )
            return image.convert("RGBA")
        except Exception:
            return None

    def _build_composite_overlay(self, original_image: Image.Image | None, result: CaseResult) -> Image.Image | None:
        if original_image is None:
            return None

        composite = original_image.copy()
        for channel in CHANNEL_LABELS:
            if not result.lesion_presence.get(channel):
                continue
            overlay_relative_path = result.overlay_paths.get(channel)
            if not overlay_relative_path:
                continue

            try:
                overlay_payload = asyncio.run(self.storage.read_bytes(overlay_relative_path))
            except Exception:
                continue

            with Image.open(BytesIO(overlay_payload)) as overlay_image:
                prepared_overlay = overlay_image.convert("RGBA")
                if prepared_overlay.size != composite.size:
                    prepared_overlay = prepared_overlay.resize(composite.size, resample=Image.BICUBIC)
                composite = Image.alpha_composite(composite, prepared_overlay)

        return composite

    def _image_to_data_uri(self, image: Image.Image | None) -> str | None:
        if image is None:
            return None

        buffer = BytesIO()
        image.save(buffer, format="PNG")
        encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
        return f"data:image/png;base64,{encoded}"

    def _build_figure_block(self, *, title: str, image_uri: str | None, fallback_message: str) -> str:
        content = (
            f'<img src="{image_uri}" alt="{escape(title)}" />'
            if image_uri is not None
            else f'<div class="figure-placeholder">{escape(fallback_message)}</div>'
        )
        return (
            '<div class="figure-card">'
            f'<p class="figure-title">{escape(title)}</p>'
            f"{content}"
            "</div>"
        )

    def _build_lesion_rows(self, result: CaseResult) -> str:
        rows: list[str] = []
        for channel, label in CHANNEL_LABELS.items():
            detected = "Yes" if result.lesion_presence.get(channel, False) else "No"
            rows.append(
                "<tr>"
                f"<td>{escape(label)}</td>"
                f'<td class="detected-{detected.lower()}">{detected}</td>'
                "</tr>"
            )
        return "".join(rows)

    def _build_notes_section(self, notes: str | None) -> str:
        if not notes:
            return ""

        return (
            '<section class="section notes-section">'
            '<h2>Clinical notes</h2>'
            f"<p>{escape(notes)}</p>"
            "</section>"
        )

    def _get_operator_name(self, case: CaseRecord) -> str:
        if getattr(case, "user", None) is not None and case.user.full_name:
            return case.user.full_name
        return "Visara Operator"

    def _format_datetime(self, value: datetime) -> str:
        formatted = value.strftime("%d %b %Y, %H:%M %Z")
        return formatted.strip() or value.isoformat()

    def _format_footer_date(self, value: datetime) -> str:
        return value.strftime("%d %b %Y")

